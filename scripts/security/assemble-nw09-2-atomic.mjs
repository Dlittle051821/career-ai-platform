// Builds the single-transaction NW09.2 / NW-F01 S3-S4 review artifact from the
// three reviewed forward files. Review-only output: it is written next to its
// sources in supabase/migrations-proposed/, never into supabase/migrations/.
//
//   node scripts/security/assemble-nw09-2-atomic.mjs          # write the artifact
//   node scripts/security/assemble-nw09-2-atomic.mjs --check  # exit 1 if it drifted
import {readFileSync,writeFileSync} from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
const dir="supabase/migrations-proposed/nw-f01-s3/";
export const ARTIFACT=dir+"NW09_2_ATOMIC_01-03.sql";
export const SOURCES=["01_internal_rpcs.sql","02_nw09_2_replacement.sql","03_review_separation_and_grants.sql"];
export const APPROVAL_SETTING="nextwise.nw09_2_atomic_approval";

// Each source has exactly one outer BEGIN; and one outer COMMIT; on their own lines.
function stripOuterTransaction(name,sql){
  const lines=sql.replace(/\r\n/g,"\n").split("\n");
  const begins=lines.flatMap((l,i)=>/^begin;\s*$/i.test(l)?[i]:[]);
  const commits=lines.flatMap((l,i)=>/^commit;\s*$/i.test(l)?[i]:[]);
  if(begins.length!==1||commits.length!==1||begins[0]>commits[0])
    throw new Error(name+": expected exactly one outer begin; and commit; line");
  const tail=lines.slice(commits[0]+1).join("\n").trim();
  if(tail)throw new Error(name+": statements after the outer commit");
  return lines.slice(begins[0]+1,commits[0]).join("\n").trim();
}

export function assemble(read=(f)=>readFileSync(path.join(root,dir,f),"utf8")){
  const parts=SOURCES.map((f)=>"-- ===== BEGIN "+f+" =====\n"+stripOuterTransaction(f,read(f))+"\n-- ===== END "+f+" =====");
  return [
"-- PROPOSED - DO NOT APPLY. Requires separate written approval and completed security gates.",
"-- REVIEW ONLY. NOT APPLIED. GENERATED by scripts/security/assemble-nw09-2-atomic.mjs; do not edit by hand.",
"-- NW09.2 + NW-F01 S3/S4 forward migration as ONE transaction: "+SOURCES.join(", ")+".",
"-- Prerequisites (must already be applied, in order): baseline 0001-0022, NW05, NW06, NW07, NW09.",
"-- Do NOT also apply NW09_2_openai_live_pilot.sql. 04_pause_ai_recovery.sql is a separate recovery tool.",
"-- 05_payment_attempt_integrity.sql is a separate, independently approved payment migration.",
"-- Run with: psql -v ON_ERROR_STOP=1 -f <this file>. It has its own single BEGIN/COMMIT; do not add -1.",
"-- The operator must opt in for this exact session before running, e.g.:",
"--   set "+APPROVAL_SETTING+" = '<approval reference for the named target>';",
"-- Any error anywhere rolls back every schema, grant and data change in this file.",
"begin;",
"set local lock_timeout = '5s';",
"set local statement_timeout = '120s';",
"do $$ begin",
"  if current_user <> 'postgres' then raise exception 'Reviewed migration owner must be postgres'; end if;",
"  if coalesce(current_setting('"+APPROVAL_SETTING+"', true), '') !~ '^[A-Za-z0-9._:-]{6,80}$' then",
"    raise exception 'Set "+APPROVAL_SETTING+" to the approval reference for this target before running';",
"  end if;",
"  if to_regclass('public.recommendation_drafts') is null or to_regclass('public.ai_generation_runs') is null",
"     or to_regprocedure('public.counsellor_has_case_access(uuid)') is null then",
"    raise exception 'Prerequisites missing: apply NW07 and NW09 first';",
"  end if;",
"end $$;",
"",
...parts,
"",
"-- Final combined postcondition: every reviewed object exists together.",
"do $$ begin",
"  if to_regclass('public.student_ai_processing_consents') is null",
"     or to_regprocedure('public.staff_finalize_ai_generation_run(uuid,uuid,uuid,uuid,jsonb,jsonb,jsonb)') is null",
"     or to_regprocedure('nextwise_security.guard_ai_draft_content()') is null",
"     or not exists(select 1 from pg_trigger where tgname='nw_f01_guard_ai_draft_content' and not tgisinternal)",
"  then raise exception 'Combined postcondition failed'; end if;",
"end $$;",
"-- @@REHEARSAL_FAILPOINT@@",
"commit;",
""].join("\n");
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const sql=assemble(),target=path.join(root,ARTIFACT);
  if(process.argv.includes("--check")){
    const current=readFileSync(target,"utf8").replace(/\r\n/g,"\n");
    if(current!==sql){console.error("Drift: "+ARTIFACT+" does not match its sources");process.exit(1);}
    console.log("OK: "+ARTIFACT+" matches "+SOURCES.join(", "));
  }else{writeFileSync(target,sql);console.log("Wrote "+ARTIFACT);}
}
