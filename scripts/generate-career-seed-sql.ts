// ---------------------------------------------------------------------------
// 12. career_industries — join target is industries, not careers, so use a
// bespoke (not the generic single-join) statement.
// ---------------------------------------------------------------------------
{
  emit(`-- ----------------------------------------------------------------------------`);
  emit(`-- 12. career_industries`);
  emit(`-- ----------------------------------------------------------------------------`);
  emit(`delete from public.career_industries`);
  emit(`where career_id in (select id from public.careers where career_key in (${allCareerKeysList}));`);
  emit("");

  const rows: string[] = [];
  for (const c of ALL_CAREERS) {
    for (const industryKey of c.industryKeys ?? []) {
      rows.push(`  (${str(c.careerKey)}, ${str(industryKey)})`);
    }
  }

  if (rows.length > 0) {
    emit(`insert into public.career_industries (career_id, industry_id)`);
    emit(`select c.id, ind.id`);
    emit(`from (values`);
    emit(rows.join(",\n"));
    emit(`) as v(career_key, industry_key)`);
    emit(`join public.careers c on c.career_key = v.career_key`);
    emit(`join public.industries ind on ind.industry_key = v.industry_key;`);
  } else {
    emit(`-- (no rows to insert for career_industries)`);
  }
  emit("");
}

// ---------------------------------------------------------------------------
// 13. career_tag_map — join target is career_tags.
// ---------------------------------------------------------------------------
{
  emit(`-- ----------------------------------------------------------------------------`);
  emit(`-- 13. career_tag_map`);
  emit(`-- ----------------------------------------------------------------------------`);
  emit(`delete from public.career_tag_map`);
  emit(`where career_id in (select id from public.careers where career_key in (${allCareerKeysList}));`);
  emit("");

  const rows: string[] = [];
  for (const c of ALL_CAREERS) {
    for (const tagKey of c.tagKeys ?? []) {
      rows.push(`  (${str(c.careerKey)}, ${str(tagKey)})`);
    }
  }

  if (rows.length > 0) {
    emit(`insert into public.career_tag_map (career_id, tag_id)`);
    emit(`select c.id, t.id`);
    emit(`from (values`);
    emit(rows.join(",\n"));
    emit(`) as v(career_key, tag_key)`);
    emit(`join public.careers c on c.career_key = v.career_key`);
    emit(`join public.career_tags t on t.tag_key = v.tag_key;`);
  } else {
    emit(`-- (no rows to insert for career_tag_map)`);
  }
  emit("");
}

// ---------------------------------------------------------------------------
// 14. career_related — manual curation only (relatedCareerKeys). Both
// endpoints resolve against public.careers via career_key.
// ---------------------------------------------------------------------------
{
  emit(`-- ----------------------------------------------------------------------------`);
  emit(`-- 14. career_related (manually curated — relatedCareerKeys)`);
  emit(`-- ----------------------------------------------------------------------------`);
  emit(`delete from public.career_related`);
  emit(`where career_id in (select id from public.careers where career_key in (${allCareerKeysList}));`);
  emit("");

  const rows: string[] = [];
  for (const c of ALL_CAREERS) {
    (c.relatedCareerKeys ?? []).forEach((rk, i) => {
      rows.push(`  (${str(c.careerKey)}, ${str(rk)}, ${num(i * 10)})`);
    });
  }

  if (rows.length > 0) {
    emit(`insert into public.career_related (career_id, related_career_id, display_order)`);
    emit(`select c.id, rc.id, v.display_order`);
    emit(`from (values`);
    emit(rows.join(",\n"));
    emit(`) as v(career_key, related_career_key, display_order)`);
    emit(`join public.careers c on c.career_key = v.career_key`);
    emit(`join public.careers rc on rc.career_key = v.related_career_key;`);
  } else {
    emit(`-- (no rows to insert for career_related)`);
  }
  emit("");
}

emit(`-- ============================================================================`);
