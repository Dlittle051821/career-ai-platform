// ---------------------------------------------------------------------------
// Generic helper: delete-then-insert a child table keyed by career_key,
// joined to public.careers on career_key to resolve career_id.
// ---------------------------------------------------------------------------
const allCareerKeysList = ALL_CAREERS.map((c) => str(c.careerKey)).join(", ");

function emitChildTable(opts: {
  sectionTitle: string;
  table: string;
  valueColumns: string[]; // columns after career_key, in VALUES order
  insertColumns: string[]; // destination columns (career_id first, then these)
  rows: (c: CareerSeed) => string[][]; // each inner array = one VALUES row's non-career_key columns (already SQL-literal strings)
}) {
  const { sectionTitle, table, valueColumns, insertColumns, rows } = opts;
  emit(`-- ----------------------------------------------------------------------------`);
  emit(`-- ${sectionTitle}`);
  emit(`-- ----------------------------------------------------------------------------`);
  emit(`delete from public.${table}`);
  emit(`where career_id in (select id from public.careers where career_key in (${allCareerKeysList}));`);
  emit("");

  const allRows: string[] = [];
  for (const c of ALL_CAREERS) {
    for (const r of rows(c)) {
      allRows.push(`  (${str(c.careerKey)}, ${r.join(", ")})`);
    }
  }

  if (allRows.length === 0) {
    emit(`-- (no rows to insert for ${table})`);
    emit("");
    return;
  }

  emit(`insert into public.${table} (${insertColumns.join(", ")})`);
  emit(`select c.id, ${valueColumns.map((col) => `v.${col}`).join(", ")}`);
  emit(`from (values`);
  emit(allRows.join(",\n"));
  emit(`) as v(career_key, ${valueColumns.join(", ")})`);
  emit(`join public.careers c on c.career_key = v.career_key;`);
  emit("");
}

