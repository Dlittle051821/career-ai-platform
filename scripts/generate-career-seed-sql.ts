function str(v: string | undefined | null): string {
  if (v === undefined || v === null) return "null";

  // Dollar-quoted literals keep long prose opaque to PostgreSQL's lexer and
  // avoid relying on apostrophe/backslash handling in copied SQL. Choose a
  // delimiter that cannot collide with the value itself.
  let tag = "seed";
  while (v.includes(`$${tag}$`)) tag += "_";
  return `$${tag}$${v}$${tag}$`;
}
function num(v: number | undefined | null): string {
  if (v === undefined || v === null) return "null";
  return String(v);
}
function bool(v: boolean | undefined): string {
  return v ? "true" : "false";
}

