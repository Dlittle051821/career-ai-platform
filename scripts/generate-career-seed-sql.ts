/**
 * Milestone 4 career seed SQL generator.
 *
 * Run with: npm run seed:generate
 *
 * Reads the TypeScript seed data (src/data/careers/index.ts + taxonomy.ts)
 * and writes a single idempotent SQL file to
 * `supabase/seed/0001_careers_seed.sql`. That file is safe to paste into
 * the Supabase SQL Editor and run — once, or many times:
 *
 *  - career_families / industries / career_tags / careers are written with
 *    `insert ... on conflict (<stable key>) do update` — re-running updates
 *    existing rows in place rather than duplicating them.
 *  - every child table (subject/interest/skill requirements, work
 *    preference profile, career priority profile, education routes,
 *    career_industries, career_tag_map, career_aliases, career_related) is
 *    written as `delete rows for these career_ids` followed by a fresh
 *    `insert` — this is the same delete-then-insert pattern used for
 *    Milestone 3 student data, and it means edits or removals in the
 *    TypeScript seed file are correctly reflected on the next seed run
 *    instead of leaving stale rows behind.
 *
 * This script does not connect to Supabase — it only reads local
 * TypeScript files and writes a local .sql file. Always run
 * `npm run validate:careers` first; this generator does not re-validate.
 */

