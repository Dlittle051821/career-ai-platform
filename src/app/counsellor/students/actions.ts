export async function createRecommendationDraftAction(studentUserId: string, _prev: ActionState, formData: FormData): Promise<ActionState> {
  const title = String(formData.get("title") ?? "").trim();
  const recommendationTypeRaw = String(formData.get("recommendationType") ?? "").trim();
  let draftId: string;
  try {
    draftId = await createRecommendationDraft({ studentUserId, title, recommendationType: recommendationTypeRaw || null }, formData);
  } catch (error) {
    return { error: friendlyAdminError(error) };
  }
  revalidatePath(`/counsellor/students/${studentUserId}`);
  revalidatePath("/counsellor/recommendations");
  revalidatePath("/counsellor");
  // Server Actions can't redirect-with-state in the same return shape this
  // form uses (useActionState) — the page's own revalidated data shows the
  // new draft immediately in the Recommendations section; the counsellor
  // opens it with its own link, same pattern staff_create_application_task's
  // own caller uses (no forced redirect, the created id is just available).
  void draftId;
  return { error: null };
}

/**
 * NW09 — request an AI-assisted FIRST DRAFT for this student. All
 * authorisation (role, case access, entitlement, consent, data policy,
 * limits, idempotency) is enforced inside requestCareerAnalysis() and the
 * NW09 reserve RPC — this wrapper only reads the form and maps the result.
 * The idempotency key is generated by the server when the page renders, so
 * a double-submit or a retried request never runs (or pays for) a second
 * analysis. Never redirects, never publishes: the result is a draft.
 */
export async function requestCareerAnalysisAction(studentUserId: string, _prev: CareerAnalysisActionState, formData: FormData): Promise<CareerAnalysisActionState> {
  const regeneratesRunId = String(formData.get("regeneratesRunId") ?? "").trim() || null;
  try {
    const config = getAiConfig();
    const outcome = await requestCareerAnalysis(
      {
        studentUserId,
        idempotencyKey: String(formData.get("idempotencyKey") ?? ""),
        consentConfirmed: formData.get("aiConsent") === "on",
        regeneratesRunId,
        regenerationReason: regeneratesRunId ? String(formData.get("regenerationReason") ?? "") : null,
      },
      createCareerIntelligenceGateway(config),
      { config, provider: getAiProvider(config, mockCareerAnalyst) },
    );
    revalidatePath(`/counsellor/students/${studentUserId}`);
    if (outcome.kind === "draft_created") {
      revalidatePath("/counsellor/recommendations");
      revalidatePath("/counsellor");
    }
    return describeOutcome(outcome);
  } catch (error) {
    if (error instanceof CareerIntelligenceUnavailableError) return { error: error.message, notice: null, draftId: null, followUpQuestions: [] };
    console.error("[counsellor/career-intelligence] request failed:", error instanceof Error ? error.name : "error");
    return { error: "The analysis could not be completed. Please try again.", notice: null, draftId: null, followUpQuestions: [] };
  }
}
